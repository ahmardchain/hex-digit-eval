"""Write RESULTS.md purely from results/<prefix>_* files (no hand-typed numbers)."""
import argparse, json, os, sys
import pandas as pd
sys.path.insert(0, "src")
from hexeval import config

ap = argparse.ArgumentParser(); ap.add_argument("--prefix", default="full"); ap.add_argument("--out", default="RESULTS.md")
a = ap.parse_args()
M = json.load(open(f"results/{a.prefix}_metrics.json"))
S = json.load(open("data/dataset_summary.json"))
resp = "results/pilot_responses.csv" if a.prefix == "pilot" else "results/responses.csv"
R = pd.read_csv(resp)
st_path = resp.replace(".csv", "_status.json")
status = json.load(open(st_path))["status"] if os.path.exists(st_path) else {}
n_items = len(pd.read_csv("data/items.csv"))


def f(x, p=3):
    return "n/a" if x is None or (isinstance(x, float) and x != x) else f"{x:.{p}f}"


def ci(d):
    return "n/a" if not d else f"{f(d['value'])} [{f(d['ci_lo'])}, {f(d['ci_hi'])}]"


L = [f"# RESULTS ({a.prefix})", "",
     "Every number below is generated by `scripts/make_results_md.py` from files in `results/`; nothing is hand-entered.",
     "95% CIs: cluster bootstrap over tokens (1000 resamples unless noted). Unit of analysis: one greedy (T=0) answer to paraphrase 0 per (token, model).", ""]
dropped = getattr(config, "DROPPED_MODELS", {}) if a.prefix != "pilot" else {}
L += ["## Run completeness", "", "| model | responses on disk | expected | status |", "|---|---|---|---|"]
exp = (n_items if a.prefix != "pilot" else 30) * 6
for m, g in R.groupby("model"):
    if m in dropped: continue
    L.append(f"| {m} | {int(g.error.isna().sum())} | {exp} | {' '.join(str(status.get(m, 'running/partial')).split())[:160]} |")
for m, why in dropped.items():
    L.append(f"| {m} (DROPPED, not reported) | {int(R[(R.model == m)].error.isna().sum()) if m in set(R.model) else 'cached only'} | {exp} | {why} |")
sp = f"results/{a.prefix}_subset.json"
if os.path.exists(sp) and a.prefix != "pilot":
    SS = json.load(open(sp))
    L += ["", "## Item set used for every metric below", "",
          ("All models completed the full design: " if SS["is_full_design"] else "**Shared pre-registered subset** (models could not all finish the full design on free tiers): ")
          + f"{SS['n_shared_items']} of {SS['n_items_full_design']} tokens, identical for all models ({', '.join(SS['models'])}).",
          f"- Subset rule (fixed before any results): items are queried in a stratum-interleaved random order (`src/hexeval/subset.py`); "
          f"the subset is the longest prefix of that order completed by every model (prefix length {SS['priority_prefix_K']}), "
          f"minus {len(SS['excluded_in_prefix_failed_calls'])} item(s) with a persistent API failure for at least one model.",
          f"- Shared items by stratum: {json.dumps(SS['shared_items_by_stratum'])} (full design {json.dumps(SS['full_items_by_stratum'])}).",
          f"- Completed tokens per model (all 6 calls): {json.dumps(SS['complete_items_per_model'])}."]
L += ["", f"Dataset: {json.dumps(S['items_by_stratum'])} (targets {json.dumps(S['targets'])}).", ""]
L += ["## Headline per model", "",
      "| model | n tokens | answered | abstain | exact-match accuracy (all) | accuracy (answered) | confident-wrong (conf≥90, of answered) | ECE | Brier | invalid-format (of answered) |",
      "|---|---|---|---|---|---|---|---|---|---|"]
for m, v in M.items():
    if m.startswith("_"): continue
    L.append(f"| {m} | {v['n_items']} | {f(v['answer_rate'])} | {f(v['abstain_rate'])} | {ci(v['accuracy_all'])} | {ci(v['accuracy_answered'])} | "
             f"{ci(v['confident_wrong_rate_answered(conf>=90)'])} | {ci(v['ece_10bin'])} | {ci(v['brier'])} | {f(v['invalid_format_rate_answered'])} |")
L += ["", "## AUROC for predicting a correct answer (answered items; n/a = fewer than 5 correct or 5 wrong)", ""]
sigs = list(next(v for k, v in M.items() if not k.startswith("_"))["auroc"].keys())
L += ["| model | " + " | ".join(sigs) + " |", "|---|" + "---|" * len(sigs)]
for m, v in M.items():
    if m.startswith("_"): continue
    L.append(f"| {m} | " + " | ".join(ci(v["auroc"][s]) for s in sigs) + " |")
L += ["", "## Accuracy by stratum", "", "| model | " + " | ".join(["top100", "rank100_1000", "rank1000plus", "base"]) + " |", "|---|---|---|---|---|"]
for m, v in M.items():
    if m.startswith("_"): continue
    L.append(f"| {m} | " + " | ".join(f(v["accuracy_by_stratum"].get(s)) for s in ["top100", "rank100_1000", "rank1000plus", "base"]) + " |")
L += ["", "## Paraphrase spread (accuracy on paraphrases 0/1/2 at T=0)", "", "| model | p0 | p1 | p2 | max−min |", "|---|---|---|---|---|"]
for m, v in M.items():
    if m.startswith("_"): continue
    pa = v["paraphrase_accuracy"]
    L.append(f"| {m} | {f(pa[0])} | {f(pa[1])} | {f(pa[2])} | {f(v['paraphrase_accuracy_spread(max-min)'])} |")
B = M["_baselines"]
L += ["", "## Baselines", "",
      "- Always-trust: AUROC 0.5 by construction; its error rate on answered items = 1 − accuracy(answered) above.",
      f"- Random mixed-case 40-hex strings passing EIP-55 (simulated, 50k): {f(B['random_mixed_case_string_eip55_pass_rate'], 5)}",
      f"- Random casing of our gold addresses passing EIP-55 (analytic mean of 2^-letters): {f(B['analytic_random_casing_of_gold_addresses_pass_rate'], 6)}",
      f"- Single case-flip of a true checksummed address passing EIP-55: {f(B['single_case_flip_of_true_address_pass_rate'], 5)}",
      "- Market-cap rank alone: see `baseline_rank_only` AUROC column.", ""]
dp = f"results/{a.prefix}_destinations.csv"
if os.path.exists(dp):
    D = pd.read_csv(dp, index_col=0)
    L += ["## Where wrong answers would send funds (counts of wrong answered greedy addresses)", "", D.to_markdown(), "",
          "Categories: invalid_format = not a 40-hex address; same_token_other_chain = this token's address on another chain; "
          "other_known_token = an address in any of our token lists; contract_code = some other contract on this chain; "
          "used_eoa = account with nonce or balance > 0; never_used = no code, nonce 0, balance 0 (funds effectively burned). "
          "Per-token detail is in `private/` only (ethics).", ""]
figs = [p for p in sorted(os.listdir("figures")) if p.startswith(a.prefix + "_")] if os.path.exists("figures") else []
L += ["## Figures", ""] + [f"- `figures/{p}`" for p in figs]
open(a.out, "w").write("\n".join(L) + "\n")
print("wrote", a.out)
